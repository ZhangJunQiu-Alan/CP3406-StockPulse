@Composable
fun SettingsIntro(modifier: Modifier = Modifier) {
    Surface(
        color = MaterialTheme.colorScheme.secondaryContainer,
        contentColor = MaterialTheme.colorScheme.onSecondaryContainer,
        shape = RoundedCornerShape(20.dp),
        modifier = modifier.fillMaxWidth(),
    ) {
        Row(
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(16.dp),
            modifier = Modifier.padding(16.dp),
        ) {
            Column(
                verticalArrangement = Arrangement.spacedBy(4.dp),
                modifier = Modifier.weight(1f),
            ) {
                Text(
                    text = stringResource(R.string.settings_intro_title),
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.SemiBold,
                )
                Text(
                    text = stringResource(R.string.settings_intro_body),
                    style = MaterialTheme.typography.bodySmall,
                )
            }
            if (LocalDensity.current.fontScale <= 1.3f) {
                Image(
                    painter = painterResource(R.drawable.illustration_watchlist),
                    contentDescription = null,
                    modifier = Modifier.size(width = 72.dp, height = 64.dp),
                )
            }
        }
    }
}
